<?php
/**
 * On-demand report downloads (Reports → Generate report).
 *
 * The user picks a report type, format (PDF, Excel, CSV), date range and — when allowed —
 * a team or member. The file is built in memory / a private temp file, streamed to the
 * browser and deleted immediately: nothing is stored on the server. Scope follows the
 * same rules as the on-screen reports (NDWD_REST::report_scope), so a member only ever
 * exports their own figures and a team manager only the teams they may report on.
 */

defined( 'ABSPATH' ) || exit;

class NDWD_Exports {

	const TYPES = array(
		'tasks'        => 'Work & tasks',
		'productivity' => 'Team performance & member-wise summary',
		'attendance'   => 'Attendance',
		'leave'        => 'Leave',
		'activity'     => 'Activity log',
	);

	const FORMATS = array( 'pdf', 'xlsx', 'csv' );

	/** Max range for one export, to keep shared hosting responsive. */
	const MAX_DAYS = 400;

	public static function export( $in, $user_id ) {
		$type   = isset( $in['type'] ) ? sanitize_key( $in['type'] ) : '';
		$format = isset( $in['format'] ) ? sanitize_key( $in['format'] ) : '';
		$from   = NDWD_Helpers::sanitize_date( isset( $in['from'] ) ? (string) $in['from'] : '' );
		$to     = NDWD_Helpers::sanitize_date( isset( $in['to'] ) ? (string) $in['to'] : '' );
		if ( ! isset( self::TYPES[ $type ] ) ) {
			return new WP_Error( 'ndwd_invalid', 'Choose a report type.', array( 'status' => 400 ) );
		}
		if ( ! in_array( $format, self::FORMATS, true ) ) {
			return new WP_Error( 'ndwd_invalid', 'Choose PDF, Excel or CSV.', array( 'status' => 400 ) );
		}
		if ( ! $from || ! $to || $from > $to ) {
			return new WP_Error( 'ndwd_invalid', 'Choose a valid date range (From must be on or before To).', array( 'status' => 400 ) );
		}
		if ( ( new DateTimeImmutable( $from ) )->diff( new DateTimeImmutable( $to ) )->days > self::MAX_DAYS ) {
			return new WP_Error( 'ndwd_invalid', 'The date range can be at most ' . self::MAX_DAYS . ' days.', array( 'status' => 400 ) );
		}
		if ( 'xlsx' === $format && ! NDWD_XLSX_Writer::available() ) {
			return new WP_Error( 'ndwd_env', 'Excel export needs the PHP ZipArchive extension. Choose CSV or PDF, or ask your host to enable it.', array( 'status' => 500 ) );
		}
		$member_id = absint( isset( $in['member_id'] ) ? $in['member_id'] : 0 );
		$team_id   = absint( isset( $in['team_id'] ) ? $in['team_id'] : 0 );
		$scope     = NDWD_REST::report_scope( $user_id, $member_id, $team_id );
		if ( is_wp_error( $scope ) ) {
			return $scope;
		}
		list( $members, $base ) = $scope;
		if ( $member_id ) {
			$base['member_id'] = $member_id;
		}
		@set_time_limit( 120 ); // phpcs:ignore
		$tables = call_user_func( array( __CLASS__, 'build_' . $type ), $from, $to, $members, $base, $user_id );
		$title  = self::TYPES[ $type ];
		$sub    = $from . ' to ' . $to . ( $team_id ? ' · Team: ' . self::name( 'teams', $team_id ) : '' ) . ( $member_id ? ' · Member: ' . NDWD_Helpers::user_name( $member_id ) : '' );
		$file   = 'neondigital-' . $type . '-' . $from . '-to-' . $to . '.' . $format;
		return NDWD_Files::send_temp( $file, function ( $path ) use ( $format, $tables, $title, $sub ) {
			return self::write( $format, $path, $tables, $title, $sub );
		} );
	}

	private static function name( $table, $id ) {
		$l = NDWD_Stats::lookup( $table );
		return isset( $l[ $id ] ) ? $l[ $id ] : '#' . $id;
	}

	/**
	 * Writes tables ( [ [title, header, rows, widths], ... ] ) as one file. CSV holds
	 * every table one after another, each with its own heading row.
	 */
	public static function write( $format, $path, $tables, $title, $sub ) {
		if ( 'xlsx' === $format ) {
			$x = new NDWD_XLSX_Writer();
			$x->add_sheet( 'About', array( 'Report', 'Value' ), array( array( 'Report', $title ), array( 'Period / filters', $sub ), array( 'Generated', NDWD_Helpers::now_mysql() . ' IST' ), array( 'Generated by', NDWD_Helpers::user_name( get_current_user_id() ) ) ) );
			foreach ( $tables as $t ) {
				$x->add_sheet( mb_substr( preg_replace( '/[\\\\\/\?\*\[\]:]/', ' ', $t[0] ), 0, 31 ), $t[1], $t[2] );
			}
			return $x->save( $path );
		}
		if ( 'csv' === $format ) {
			$fh = @fopen( $path, 'w' ); // phpcs:ignore
			if ( ! $fh ) {
				return new WP_Error( 'ndwd_csv', 'Could not write the CSV file.' );
			}
			fwrite( $fh, "\xEF\xBB\xBF" );
			fputcsv( $fh, array( $title, $sub ) );
			foreach ( $tables as $i => $t ) {
				if ( count( $tables ) > 1 ) {
					fputcsv( $fh, array() );
					fputcsv( $fh, array( $t[0] ) );
				}
				fputcsv( $fh, $t[1] );
				foreach ( $t[2] as $r ) {
					fputcsv( $fh, array_map( array( 'NDWD_Reports', 'csv_safe' ), array_values( (array) $r ) ) );
				}
			}
			fclose( $fh );
			return true;
		}
		$pdf = new NDWD_PDF_Writer( $title );
		$pdf->heading( $title, 18 );
		$pdf->paragraph( $sub . ' · Asia/Kolkata', 9 );
		foreach ( $tables as $t ) {
			$pdf->heading( $t[0], 12 );
			if ( ! $t[2] ) {
				$pdf->paragraph( 'No records in this period.', 9 );
				continue;
			}
			$pdf->table( $t[1], $t[2], isset( $t[3] ) ? $t[3] : array(), count( $t[1] ) > 9 ? 7 : 8 );
		}
		return $pdf->save( $path );
	}

