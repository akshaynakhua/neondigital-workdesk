<?php
/**
 * File delivery: protected storage folders, authenticated streaming and signed links.
 *
 * Downloads inside the app go through REST routes (cookie + X-WP-Nonce) and are
 * fetched by the browser with fetch(), so a failure shows a message with Retry
 * instead of a WordPress error page. Links meant for people outside WorkDesk (an
 * invoice PDF sent to a client, the monthly report ZIP sent to the Admin) are
 * HMAC-signed, expire, and point at one specific file only.
 */

defined( 'ABSPATH' ) || exit;

class NDWD_Files {

	const TYPES = array(
		'xlsx' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
		'csv'  => 'text/csv; charset=utf-8',
		'pdf'  => 'application/pdf',
		'zip'  => 'application/zip',
		'png'  => 'image/png',
		'jpg'  => 'image/jpeg',
		'jpeg' => 'image/jpeg',
		'webp' => 'image/webp',
		'txt'  => 'text/plain; charset=utf-8',
	);

	public static function init() {
		add_action( 'template_redirect', array( __CLASS__, 'maybe_signed_download' ), 0 );
		add_action( 'wp_ajax_ndwd_nonce', array( __CLASS__, 'fresh_nonce' ) );
	}

	/**
	 * Returns a fresh REST nonce to a signed-in user whose page has been open so long
	 * that its nonce expired. Same-origin only (no CORS headers), so other sites
	 * cannot read it.
	 */
	public static function fresh_nonce() {
		nocache_headers();
		if ( ! is_user_logged_in() || ! NDWD_Permissions::can( 'ndwd_access' ) ) {
			wp_send_json_error( array( 'message' => 'Signed out' ), 401 );
		}
		wp_send_json_success( array( 'nonce' => wp_create_nonce( 'wp_rest' ) ) );
	}

	/** A protected sub-folder of the reports storage folder. */
	public static function dir( $sub ) {
		$dir = NDWD_Reports::base_dir() . '/' . trim( $sub, '/' );
		if ( ! is_dir( $dir ) ) {
			wp_mkdir_p( $dir );
		}
		NDWD_Reports::protect( $dir );
		return $dir;
	}

	/** Absolute path of a storage-relative path, or null when it escapes the storage folder. */
	public static function path( $rel ) {
		$base = realpath( NDWD_Reports::base_dir() );
		$path = realpath( NDWD_Reports::base_dir() . '/' . ltrim( (string) $rel, '/' ) );
		if ( ! $base || ! $path || 0 !== strpos( $path, $base . DIRECTORY_SEPARATOR ) || ! is_readable( $path ) ) {
			return null;
		}
		return $path;
	}

	public static function type_of( $name ) {
		$ext = strtolower( pathinfo( $name, PATHINFO_EXTENSION ) );
		return isset( self::TYPES[ $ext ] ) ? self::TYPES[ $ext ] : 'application/octet-stream';
	}

	private static function headers( $name, $length, $inline = false ) {
		while ( ob_get_level() ) {
			ob_end_clean();
		}
		nocache_headers();
		header( 'Content-Type: ' . self::type_of( $name ) );
		$safe = str_replace( array( '"', "\r", "\n" ), '', basename( $name ) );
		header( 'Content-Disposition: ' . ( $inline ? 'inline' : 'attachment' ) . '; filename="' . $safe . '"; filename*=UTF-8\'\'' . rawurlencode( $safe ) );
		header( 'Content-Length: ' . $length );
		header( 'X-Content-Type-Options: nosniff' );
		header( 'Access-Control-Expose-Headers: Content-Disposition' );
	}

	/** Streams a file and ends the request. */
	public static function send_file( $path, $name, $inline = false ) {
		self::headers( $name, filesize( $path ), $inline );
		readfile( $path ); // phpcs:ignore
		exit;
	}

	/** Streams generated bytes and ends the request (nothing is kept on the server). */
	public static function send_bytes( $bytes, $name ) {
		self::headers( $name, strlen( $bytes ) );
		echo $bytes; // phpcs:ignore
		exit;
	}

	/** Builds a file in a private temp path, streams it and deletes it. $build( $path ) returns true|WP_Error. */
	public static function send_temp( $name, $build ) {
		$dir  = self::dir( 'tmp' );
		$path = $dir . '/' . wp_generate_password( 16, false ) . '-' . sanitize_file_name( $name );
		$ok   = call_user_func( $build, $path );
		if ( true !== $ok || ! file_exists( $path ) ) {
			@unlink( $path ); // phpcs:ignore
			return is_wp_error( $ok ) ? $ok : new WP_Error( 'ndwd_export', 'The file could not be generated.', array( 'status' => 500 ) );
		}
		$bytes = file_get_contents( $path ); // phpcs:ignore
		@unlink( $path ); // phpcs:ignore
		self::send_bytes( $bytes, $name );
	}

	/** Deletes temporary files older than $hours. Returns the number removed. */
	public static function clean_tmp( $hours = 2 ) {
		$n = 0;
		foreach ( (array) glob( self::dir( 'tmp' ) . '/*' ) as $f ) {
			if ( is_file( $f ) && ! in_array( basename( $f ), array( 'index.php', '.htaccess', 'web.config' ), true ) && filemtime( $f ) < time() - $hours * 3600 ) {
				@unlink( $f ); // phpcs:ignore
				$n++;
			}
		}
		return $n;
	}

	/* ------------------------------------------------------------------ *
	 * Signed links
	 * ------------------------------------------------------------------ */

	private static function secret() {
		$s = get_option( 'ndwd_link_secret' );
		if ( ! $s ) {
			$s = wp_generate_password( 64, true, true );
			add_option( 'ndwd_link_secret', $s, '', false );
			$s = get_option( 'ndwd_link_secret' );
		}
		return $s . wp_salt( 'auth' );
	}

	private static function b64( $s ) {
		return rtrim( strtr( base64_encode( $s ), '+/', '-_' ), '=' );
	}

	/** A link that downloads one item without signing in, until $days have passed. */
	public static function signed_url( $kind, $id, $days = 30, $extra = '' ) {
		$payload = self::b64( wp_json_encode( array( 'k' => $kind, 'i' => (int) $id, 'e' => time() + $days * DAY_IN_SECONDS, 'x' => $extra ) ) );
		$sig     = self::b64( hash_hmac( 'sha256', $payload, self::secret(), true ) );
		return add_query_arg( 'ndwd_file', $payload . '.' . $sig, home_url( '/' ) );
	}

	/** @return array|null Verified payload. */
	public static function verify( $token ) {
		$parts = explode( '.', (string) $token );
		if ( 2 !== count( $parts ) ) {
			return null;
		}
		$expect = self::b64( hash_hmac( 'sha256', $parts[0], self::secret(), true ) );
		if ( ! hash_equals( $expect, $parts[1] ) ) {
			return null;
		}
		$data = json_decode( base64_decode( strtr( $parts[0], '-_', '+/' ) ), true );
		if ( ! is_array( $data ) || empty( $data['e'] ) || $data['e'] < time() ) {
			return null;
		}
		return $data;
	}

	public static function maybe_signed_download() {
		if ( empty( $_GET['ndwd_file'] ) ) { // phpcs:ignore
			return;
		}
		$data = self::verify( sanitize_text_field( wp_unslash( $_GET['ndwd_file'] ) ) ); // phpcs:ignore
		if ( ! $data ) {
			wp_die( 'This download link is invalid or has expired. Please ask NeonDigital for a new link.', 'Link expired', array( 'response' => 410 ) );
		}
		$res = null;
		if ( 'invoice' === $data['k'] ) {
			$res = NDWD_Accounts::stream_invoice_pdf( $data['i'], true );
		} elseif ( 'report_zip' === $data['k'] ) {
			$res = NDWD_Reports::stream_zip( $data['i'] );
		}
		$msg = is_wp_error( $res ) ? $res->get_error_message() : 'File not found.';
		wp_die( esc_html( $msg ), 'Not available', array( 'response' => 404 ) );
	}
}
